public class Number {
    public static void main(String[] args) {
      
        System.out.println("Number\tSquare\tCube\n");
        for (int i = 0 ; i <= 3 ; i++) {
            int square = i * i;
            int cube = i * i * i;
          
        System.out.println( i + "\t" + square + "\t" + cube);
        } 
    }
}
